#!/usr/bin/env node
import { readFile, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { createHash } from "node:crypto";
import { dirname, relative, resolve } from "node:path";
import ts from "typescript";

const root = process.cwd();
const check = process.argv.includes("--check");
const outPath = "docs/reference/api-report.md";
const entrypoints = [
  { packageName: "activefs", file: "packages/activefs/src/index.ts" },
  { packageName: "@activefs/core", file: "packages/core/src/index.ts" },
  { packageName: "@activefs/config", file: "packages/config/src/index.ts" },
  { packageName: "@activefs/source-http", file: "packages/source-http/src/index.ts" },
  { packageName: "@activefs/local", file: "packages/local/src/index.ts" },
  { packageName: "@activefs/mount", file: "packages/mount/src/index.ts" },
  { packageName: "@activefs/mcp", file: "packages/mcp/src/index.ts" },
  { packageName: "@activefs/testing", file: "packages/testing/src/index.ts" },
  { packageName: "@activefs/testing/conformance", file: "packages/testing/src/conformance.ts" },
  { packageName: "@activefs/cli", file: "packages/cli/src/index.ts" }
];

const report = await renderReport();

if (check) {
  if (!existsSync(outPath)) {
    console.error(`${outPath} does not exist. Run pnpm api:report.`);
    process.exit(1);
  }
  const current = await readFile(outPath, "utf8");
  if (current !== report) {
    console.error(`${outPath} is stale. Run pnpm api:report.`);
    process.exit(1);
  }
} else {
  await writeFile(outPath, report);
}

async function renderReport() {
  const sections = [];
  for (const entrypoint of entrypoints) {
    const exports = await collectExports(entrypoint.file);
    sections.push(renderEntrypoint(entrypoint, exports));
  }

  const body = [
    "# ActiveFS API Report",
    "",
    "<!-- Generated by scripts/generate-api-report.mjs. Do not edit by hand. -->",
    "",
    `Source fingerprint: ${fingerprint(sections.join("\n"))}`,
    "",
    "This report lists the exported declarations from each package entrypoint and",
    "fails in check mode when the tracked report is stale.",
    "",
    ...sections
  ].join("\n");
  return `${body}\n`;
}

async function collectExports(file, seen = new Set()) {
  const absolute = resolve(root, file);
  if (seen.has(absolute)) {
    return [];
  }
  seen.add(absolute);
  const sourceText = await readFile(file, "utf8");
  const sourceFile = ts.createSourceFile(file, sourceText, ts.ScriptTarget.Latest, true);
  const exports = [];
  visitTopLevel(sourceFile, sourceFile, exports);
  for (const child of sourceFile.statements ?? []) {
    if (!ts.isExportDeclaration(child) || child.exportClause) {
      continue;
    }
    if (!child.moduleSpecifier || !ts.isStringLiteral(child.moduleSpecifier)) {
      continue;
    }
    const target = resolveExportTarget(file, child.moduleSpecifier.text);
    if (!target) {
      continue;
    }
    exports.push(...await collectExports(target, seen));
  }
  return dedupeExports(exports);
}

function resolveExportTarget(fromFile, specifier) {
  if (!specifier.startsWith(".")) {
    return undefined;
  }
  const base = resolve(dirname(resolve(root, fromFile)), specifier.replace(/\.js$/, ".ts"));
  const candidates = [
    base,
    `${base}.ts`,
    resolve(base, "index.ts")
  ];
  for (const candidate of candidates) {
    if (existsSync(candidate)) {
      return relative(root, candidate);
    }
  }
  return undefined;
}

function dedupeExports(exports) {
  const byDeclaration = new Map();
  for (const item of exports) {
    byDeclaration.set(`${item.kind}:${item.name}`, item);
  }
  return [...byDeclaration.values()];
}

function visitTopLevel(sourceFile, node, exports) {
  for (const child of node.statements ?? []) {
    if (!isExportedDeclaration(child)) {
      continue;
    }
    if (ts.isVariableStatement(child)) {
      for (const declaration of child.declarationList.declarations) {
        exports.push({
          kind: "const",
          name: declaration.name.getText(sourceFile),
          summary: firstDocSummary(child) ?? firstDocSummary(declaration),
          members: []
        });
      }
      continue;
    }
    exports.push({
      kind: declarationKind(child),
      name: declarationName(child, sourceFile),
      summary: firstDocSummary(child),
      members: memberNames(child, sourceFile)
    });
  }
}

function renderEntrypoint(entrypoint, exports) {
  const lines = [
    `## ${entrypoint.packageName}`,
    "",
    `Entrypoint: \`${relative(root, entrypoint.file)}\``,
    ""
  ];
  for (const item of exports.sort(compareExports)) {
    lines.push(`- \`${item.kind} ${item.name}\`${item.summary ? ` - ${item.summary}` : ""}`);
    if (item.members.length > 0) {
      lines.push(`  - public members: ${item.members.map((member) => `\`${member}\``).join(", ")}`);
    }
  }
  lines.push("");
  return lines.join("\n");
}

function isExportedDeclaration(node) {
  if (
    !(
      ts.isInterfaceDeclaration(node) ||
      ts.isTypeAliasDeclaration(node) ||
      ts.isClassDeclaration(node) ||
      ts.isFunctionDeclaration(node) ||
      ts.isVariableStatement(node)
    )
  ) {
    return false;
  }
  return Boolean(ts.getCombinedModifierFlags(node) & ts.ModifierFlags.Export);
}

function declarationKind(node) {
  if (ts.isInterfaceDeclaration(node)) {
    return "interface";
  }
  if (ts.isTypeAliasDeclaration(node)) {
    return "type";
  }
  if (ts.isClassDeclaration(node)) {
    return "class";
  }
  if (ts.isFunctionDeclaration(node)) {
    return node.modifiers?.some((modifier) => modifier.kind === ts.SyntaxKind.AsyncKeyword)
      ? "async function"
      : "function";
  }
  return "export";
}

function declarationName(node, sourceFile) {
  return node.name?.getText(sourceFile) ?? "<anonymous>";
}

function memberNames(node, sourceFile) {
  if (!ts.isInterfaceDeclaration(node) && !ts.isClassDeclaration(node)) {
    return [];
  }
  const names = node.members
    .filter((member) =>
      (ts.isMethodDeclaration(member) || ts.isMethodSignature(member)) &&
      !isPrivateOrProtected(member)
    )
    .map((member) => member.name.getText(sourceFile));
  return [...new Set(names)].sort();
}

function isPrivateOrProtected(node) {
  const flags = ts.getCombinedModifierFlags(node);
  return Boolean(flags & (ts.ModifierFlags.Private | ts.ModifierFlags.Protected));
}

function firstDocSummary(node) {
  const docs = ts.getJSDocCommentsAndTags(node);
  for (const doc of docs) {
    const text = doc.comment;
    if (typeof text === "string" && text.trim()) {
      return text.trim().split(/\r?\n\s*\r?\n/, 1)[0].replace(/\s+/g, " ");
    }
  }
  return undefined;
}

function compareExports(left, right) {
  return left.name.localeCompare(right.name) || left.kind.localeCompare(right.kind);
}

function fingerprint(value) {
  return createHash("sha256").update(value).digest("hex");
}
